async fn get_crtsh_subdomains(domain: &str) -> Result<Vec<String>, Box<dyn std::error::Error>> {
    let client = Client::new();
    let url = format!("https://crt.sh/?q=%.{}&output=json", domain);
    
    let response = client.get(&url).send().await?;
    let json: Vec<serde_json::Value> = response.json().await?;
    
    let mut subdomains = HashSet::new();
    
    for entry in json {
        if let Some(name_value) = entry.get("name_value") {
            if let Some(name) = name_value.as_str() {
                // Split by newlines and process each certificate name
                for cert_name in name.lines() {
                    let cleaned = cert_name.trim();
                    if cleaned.ends_with(domain) && !cleaned.starts_with("*.") {
                        subdomains.insert(cleaned.to_string());
                    }
                }
            }
        }
    }
    
    Ok(subdomains.into_iter().collect())
}

