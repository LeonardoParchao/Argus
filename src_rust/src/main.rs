#[derive(Serialize, Deserialize)]
struct SubdomainResult {
    #[serde(rename = "type")]
    result_type: String,
    value: String,
}

#[derive(Serialize, Deserialize)]
struct PortResult {
    #[serde(rename = "type")]
    result_type: String,
    port: u16,
    service: String,
    status: String,
}

#[tokio::main]
async fn main() {
    let args: Vec<String> = env::args().collect();
    
    if args.len() < 5 {
        eprintln!("Usage: {} --target <domain> --mode <scan|subdomain|port>", args[0]);
        std::process::exit(1);
    }
    
    let target = &args[2];
    let mode = &args[4];
    
    match mode.as_str() {
        "scan" => {
            // Run both subdomain enumeration and port scanning
            enumerate_subdomains(target).await;
            scan_ports(target).await;
        }
        "subdomain" => {
            enumerate_subdomains(target).await;
        }
        "port" => {
            scan_ports(target).await;
        }
        _ => {
            eprintln!("Unknown mode: {}. Use 'scan', 'subdomain', or 'port'", mode);
            std::process::exit(1);
        }
    }
}

